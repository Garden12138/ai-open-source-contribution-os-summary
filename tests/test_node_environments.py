class FakeNodeDependencies(_FakeDependencyRuntime):
    async def prepare(self, **kwargs):
        self.recipe = kwargs["signed_plan"].plan.node_environment
        self.image = kwargs["signed_plan"].plan.builder_image_digest or kwargs["signed_plan"].plan.runner_image_digest
        return await super().prepare(**kwargs)

    async def _run(self, argv, **kwargs):
        value = json.loads(await super()._run(argv, **kwargs))
        value["environment_receipt"] = {"version": "node-environment-result-v1", "recipe": self.recipe,
            "execution_image_digest": self.image,
            "runtime_version": "22.0.0", "runtime_bin": "/usr/local/bin",
            "manager_version": self.recipe["manager_version"], "manifest_hashes": {}, "built_offline": True}
        return json.dumps(value).encode()


def node_files(manager="yarn", version="1.22.22"):
    dependency = "workspace:*" if manager in {"pnpm", "yarn"} and version != "1.22.22" else "*"
    root = {"name": "environment-fixture", "version": "1.0.0", "private": True, "type": "module",
            "packageManager": manager + "@" + version, "engines": {"node": ">=18"},
            "workspaces": ["packages/*"], "dependencies": {"@fixture/lib": dependency},
            "scripts": {"test": "node test.mjs", "prepare": "node prepare.cjs"}}
    files = {"package.json": json.dumps(root),
        "packages/lib/package.json": json.dumps({"name": "@fixture/lib", "version": "1.0.0", "type": "module", "exports": "./index.js"}),
        "packages/lib/index.js": "export const value = 'before';\n",
        "prepare.cjs": "require('fs').writeFileSync('generated.txt', require('fs').readFileSync('packages/lib/index.js'));\n",
        "test.mjs": "import assert from 'node:assert/strict'; import fs from 'node:fs'; import {value} from '@fixture/lib'; const source=fs.readFileSync('packages/lib/index.js','utf8'); assert.equal(value,source.includes(\"'after'\")?'after':'before'); assert.equal(fs.readFileSync('generated.txt','utf8'),source); fs.mkdirSync('node_modules/.vite-temp',{recursive:true}); fs.writeFileSync('node_modules/.vite-temp/config.mjs',source); console.log(value);\n"}
    if manager == "npm":
        files["package-lock.json"] = json.dumps({"name": root["name"], "version": "1.0.0", "lockfileVersion": 3,
            "requires": True, "packages": {"": root,
                "node_modules/@fixture/lib": {"resolved": "packages/lib", "link": True},
                "packages/lib": {"name": "@fixture/lib", "version": "1.0.0"}}})
    elif manager == "pnpm":
        files["pnpm-workspace.yaml"] = "packages:\n  - 'packages/*'\n"
        files["pnpm-lock.yaml"] = "lockfileVersion: '9.0'\nsettings:\n  autoInstallPeers: true\n  excludeLinksFromLockfile: false\nimporters:\n  .:\n    dependencies:\n      '@fixture/lib':\n        specifier: workspace:*\n        version: link:packages/lib\n  packages/lib: {}\n"
    elif version == "1.22.22":
        files["yarn.lock"] = "# yarn lockfile v1\n"
    else:
        files["yarn.lock"] = '# This file is generated by running "yarn install" inside your project.\n# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 8\n  cacheKey: 10c0\n\n"@fixture/lib@workspace:*, @fixture/lib@workspace:packages/lib":\n  version: 0.0.0-use.local\n  resolution: "@fixture/lib@workspace:packages/lib"\n  languageName: unknown\n  linkType: soft\n\n"environment-fixture@workspace:.":\n  version: 0.0.0-use.local\n  resolution: "environment-fixture@workspace:."\n  dependencies:\n    "@fixture/lib": "workspace:*"\n  languageName: unknown\n  linkType: soft\n'
        files[".yarnrc.yml"] = "nodeLinker: pnp\n"
    return files


def selected(files):
    evidence = {"inventory": sorted(files), "entries": [{"path": p, "content": text,
        "prior_hash": hashlib.sha256(text.encode()).hexdigest(), "executable": False} for p, text in files.items()]}
    return inspect_environment(environment_plan(list(files), change_paths=["packages/lib/index.js"]), evidence)


def test_dependency_hash_ignores_link_target_existence_but_detects_real_changes(tmp_path):
    import ast
    import stat
    from app.sandbox_worker.verification import _VERIFY_SCRIPT
    function = next(n for n in ast.parse(_VERIFY_SCRIPT).body
        if isinstance(n, ast.FunctionDef) and n.name == "dependency_inventory_hash")
    dependencies = tmp_path / "dependencies"
    dependencies.mkdir()
    target = tmp_path / "source" / "package"
    (dependencies / "z-workspace").symlink_to(target, target_is_directory=True)
    metadata = dependencies / "a-metadata"
    metadata.write_text("immutable")
    class Root(ast.NodeTransformer):
        def visit_Constant(self, node):
            return ast.copy_location(ast.Constant(str(dependencies)), node) if node.value == "/dependencies/output" else node
    module = ast.fix_missing_locations(Root().visit(ast.Module(body=[function], type_ignores=[])))
    namespace = {"os": os, "stat": stat, "hashlib": hashlib, "json": json,
        "specification": {"node_environment": {}},
        "file_evidence": lambda path: (hashlib.sha256(Path(path).read_bytes()).hexdigest(), Path(path).stat().st_size)}
    exec(compile(module, "trusted-inventory-function", "exec"), namespace)
    digest = namespace["dependency_inventory_hash"]
    original = digest()
    target.mkdir(parents=True)
    (target / "index.js").write_text("current source")
    assert digest() == original
    metadata.write_text("modified")
    assert digest() != original
    metadata.write_text("immutable")
    (dependencies / "z-workspace").unlink()
    (dependencies / "z-workspace").symlink_to(target.parent, target_is_directory=True)
    assert digest() != original


