def test_fresh_execution_view_preserves_source_and_receipt_and_detects_source_changes(tmp_path, monkeypatch):
    import subprocess
    from types import SimpleNamespace
    def probe(argv, **kwargs):
        kwargs["stdout"].write(b"v22.0.0\n" if argv[0] == "node" else b"1.22.22\n")
        return SimpleNamespace(returncode=0)
    monkeypatch.setattr(subprocess, "run", probe)
    files = node_files()
    recipe = selected(files)["node_environment"]
    recipe["workspace_lifecycle"] = []  # No repository command executes on the host.
    source, output, scratch = (tmp_path / name for name in ("source", "output", "scratch"))
    for p, text in files.items():
        path = source / p
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    (output / "project/node_modules/some-package").mkdir(parents=True)
    (output / "project/node_modules/some-package/index.js").write_text("frozen package")
    (output / "node-environment.json").write_text(json.dumps({"version": "node-environment-result-v1",
        "recipe": recipe, "runtime_version": "22.0.0", "runtime_bin": "/usr/local/bin",
        "manager_version": recipe["manager_version"], "built_offline": True,
        "manifest_hashes": {}, "execution_image_digest": "sha256:" + "a" * 64}))
    directory, environment, originals = prepare_node_execution(str(source), str(output), str(scratch), recipe, {})
    assert Path(directory, "node_modules").is_dir() and not Path(directory, "node_modules").is_symlink()
    assert Path(directory, "node_modules/some-package").is_symlink()
    Path(directory, "node_modules/.vite-temp").mkdir()
    Path(directory, "node_modules/.vite-temp/config.mjs").write_text("temporary config")
    assert not (output / "project/node_modules/.vite-temp").exists()
    assert environment["npm_config_offline"] == "true"
    assert environment["TMPDIR"] == str(scratch / "tmp")
    assert environment["XDG_CACHE_HOME"] == str(scratch / "cache")
    assert environment["HOME"] == str(scratch / "home")
    verify_node_source(directory, originals)
    Path(directory, "generated.txt").write_text("temporary output")
    verify_node_source(directory, originals)
    Path(directory, "packages/lib/index.js").write_text("tampered")
    with pytest.raises(ValueError): verify_node_source(directory, originals)
    assert (source / "packages/lib/index.js").read_text() == files["packages/lib/index.js"]


@pytest.mark.skipif(os.getenv("CONTRIBOS_RUN_DOCKER_ACCEPTANCE") != "1", reason="real containers are opt-in")
@pytest.mark.parametrize("manager,version", [("npm", "10.9.4"), ("yarn", "1.22.22"), ("yarn", "4.9.2"), ("pnpm", "10.11.0")])
def test_real_node_workspace_baseline_implementation_and_fresh_verify(tmp_path, manager, version):
    from app.sandbox_worker.explore import RepositoryArchive
    from app.sandbox_worker.implementation import (DockerImplementRuntime, ImplementationChangeSet,
        ChangeOperation, ChangeOperationKind)
    files = node_files(manager, version)
    image = os.environ["CONTRIBOS_SANDBOX_RUNNER_IMAGE"]
    archive_path = tmp_path / "repository.tar.gz"
    with tarfile.open(archive_path, "w:gz") as archive:
        for path, text in files.items():
            entry = tarfile.TarInfo("fixture-" + "a" * 40 + "/" + path)
            entry.size, entry.mode = len(text.encode()), 0o644
            archive.addfile(entry, io.BytesIO(text.encode()))
    archive = RepositoryArchive(repository_full_name="fixture/fixture", base_commit_sha="a" * 40,
        archive_hash=hashlib.sha256(archive_path.read_bytes()).hexdigest(), path=archive_path, size_bytes=archive_path.stat().st_size)
    inventory = [{"path": p, "type": "file", "size": len(text.encode()),
        "sha256": hashlib.sha256(text.encode()).hexdigest(), "executable": False} for p, text in sorted(files.items())]
    expected_inventory = content_hash(inventory)
    plan = dependency_plan(files, image, expected_inventory)
    environment = {k: os.environ[k] for k in ("HOME", "PATH", "TMPDIR", "DOCKER_HOST", "DOCKER_CONTEXT", "DOCKER_CERT_PATH", "DOCKER_CONFIG", "DOCKER_TLS_VERIFY") if k in os.environ}
    policy = SandboxPolicy()
    materializer = DockerImplementRuntime(docker_environment=environment)
    dependencies = DockerDependencyRuntime(docker_environment=environment)
    proxy = DockerDependencyProxyRuntime(docker_environment=environment)
    verifier = DockerVerifyRuntime(docker_environment=environment)
    signer = DependencyPlanSigner(key_id="node-acceptance", signing_key=b"n" * 32)
    proxy_policy = DependencyProxyPolicy.for_ecosystem("node")
    async def run():
        workspace = await materializer.create_workspace(image_digest=image, policy=policy)
        lease = dependency = None
        try:
            await materializer.materialize(workspace=workspace, archive=archive, policy=policy)
            lease = await proxy.start(image_digest=image, policy=proxy_policy)
            dependency = await dependencies.prepare(signed_plan=signer.sign(plan), signer=signer,
                repository_volume=workspace.volume_name, proxy_policy=proxy_policy, proxy_lease=lease, sandbox_policy=policy)
            await proxy.stop(lease); lease = None
            command = SandboxCommand(command_id="workspace-regression", argv=(manager, "run", "test"))
            before = await verifier.run(workspace=replace(workspace, inventory_hash=expected_inventory),
                commands=(command,), policy=policy, dependency_workspace=dependency.workspace)
            assert before.command_evidence[0].exit_code == 0, before.command_evidence[0]
            assert "before" in before.command_evidence[0].stdout_log
            path = "packages/lib/index.js"
            change = ImplementationChangeSet(change_set_id="node-change", plan_version_id="node-plan",
                plan_content_hash="4" * 64, plan_record_hash="5" * 64,
                operations=(ChangeOperation(path=path, kind=ChangeOperationKind.WRITE,
                    expected_prior_hash=hashlib.sha256(files[path].encode()).hexdigest(),
                    content=files[path].replace("before", "after"), executable=False),))
            changed = await materializer.apply(workspace=workspace, change_set=change, allowed_change_paths=(path,), policy=policy)
            after = await verifier.run(workspace=replace(workspace, inventory_hash=changed.result_inventory_hash),
                commands=(command,), policy=policy, dependency_workspace=dependency.workspace)
            assert after.command_evidence[0].exit_code == 0, after.command_evidence[0]
            assert "after" in after.command_evidence[0].stdout_log
            assert before.before_inventory_hash == before.after_inventory_hash == expected_inventory
            assert after.before_inventory_hash == after.after_inventory_hash == changed.result_inventory_hash
            assert {e.path for e in changed.result_inventory} == set(files)
        finally:
            if lease: await proxy.stop(lease, ignore_missing=True)
            if dependency: await dependencies.destroy(dependency.workspace, ignore_missing=True)
            await materializer.destroy(workspace)
    asyncio.run(run())
