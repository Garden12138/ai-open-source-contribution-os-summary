@pytest.mark.parametrize("manager,version", [("yarn", "1.22.22"), ("pnpm", "10.11.0")])
def test_only_declared_workspaces_initialize_and_runtime_pin_is_frozen(manager, version):
    files = node_files(manager, version)
    files["examples/unrelated/package.json"] = json.dumps({"scripts": {"prepare": "unexpected"}})
    files[".node-version"] = "20.19.0\n"
    environment = selected(files)
    assert environment["status"] == "supported"
    assert environment["node_environment"]["package_roots"] == [".", "packages/lib"]
    assert environment["node_environment"]["runtime_pin"] == "20.19.0"
    assert all(p["directory"] != "examples/unrelated" for p in environment["node_environment"]["workspace_lifecycle"])
    assert "examples/unrelated/package.json" in environment["manifests"]


def dependency_plan(files, image="sha256:" + "1" * 64, inventory="2" * 64):
    environment = selected(files)
    assert environment["status"] == "supported", environment
    return DependencyPreparationPlan(plan_id="node-environment-test", execution_attempt_id="node-attempt",
        implement_result_hash="3" * 64, workspace_inventory_hash=inventory, ecosystem="node",
        manifests=tuple(DependencyManifest(p, hashlib.sha256(files[p].encode()).hexdigest()) for p in environment["manifests"]),
        runner_image_digest=image, sandbox_policy_hash=SandboxPolicy().policy_hash,
        proxy_policy_hash=DependencyProxyPolicy.for_ecosystem("node").policy_hash,
        disk_bytes=SandboxPolicy().disk_bytes, version="workspace-dependency-plan-v5", source_kind="explore",
        project_directory=environment["project_directory"], preparation_version=environment["preparation_version"],
        node_environment=environment["node_environment"])


