def test_source_scope_excludes_credential_paths_without_losing_workspace_siblings():
    files = node_files()
    files.update({".npmrc": "credentialcanary", "packages/lib/.env": "credentialcanary", "packages/other/file.ts": "ok"})
    scope = selected_workspace_paths(selected(files), set(files), {"packages/lib/index.js"})
